      _model.pageSummary =
          functions.expenseSummary(_model.initExpenseDocs!.toList());
      safeSetState(() {});
      if (FFAppState().outletDetails.outletId != null &&
          FFAppState().outletDetails.outletId != '') {
        if (functions.checkPermissions(
            Permissions.CRM_ATTENDANCE_MARK.name,
            FFAppState()
                .userDoc
                .permissions
                .where((e) => e.outletId == FFAppState().outletDetails.outletId)
                .toList()
                .firstOrNull
                ?.outletPermissions
                ?.toList())!) {
          if (!isWeb) {
            _model.attendenceCheck = await queryAttendanceRecordOnce(
              parent: FFAppState().outletDetails.outletIdRef,
              queryBuilder: (attendanceRecord) => attendanceRecord
                  .where(
                    'userId',
                    isEqualTo: FFAppState().userDoc.id,
                  )
                  .where(
                    'dayId',
                    isEqualTo: dateTimeFormat(
                      "dd-MM-y",
                      getCurrentTimestamp,
                      locale: FFLocalizations.of(context).languageCode,
                    ),
                  ),
              singleRecord: true,
            ).then((s) => s.firstOrNull);
            _model.leaveDoc = await queryLeaveApplicationRecordOnce(
              parent: FFAppState().outletDetails.outletIdRef,
              queryBuilder: (leaveApplicationRecord) => leaveApplicationRecord
                  .where(
                    'userProfileId',
                    isEqualTo: FFAppState().userDoc.id,
                  )
                  .where(
                    'toDate',
                    isGreaterThanOrEqualTo:
                        functions.returnCurrentDate().millisecondsSinceEpoch,
                  ),
            );
            _model.checkleave = await actions.checkOnLeave(
              context,
              _model.leaveDoc!.toList(),
            );
            if (_model.checkleave!) {
              return;
            }
            if (_model.attendenceCheck != null) {
              if (_model.attendenceCheck?.checkInTime == 0) {
                await showDialog(
                  context: context,
                  builder: (dialogContext) {
                    return Dialog(
                      elevation: 0,
                      insetPadding: EdgeInsets.zero,
                      backgroundColor: Colors.transparent,
                      alignment: AlignmentDirectional(0.0, 0.0)
                          .resolve(Directionality.of(context)),
                      child: GestureDetector(
                        onTap: () {
                          FocusScope.of(dialogContext).unfocus();
                          FocusManager.instance.primaryFocus?.unfocus();
                        },
                        child: CheckinpopupWidget(),
                      ),
                    );
                  },
                );
              } else {
                if (_model.attendenceCheck?.checkOutTime == 0) {
                  if (functions.checkPermissions(
                          Permissions.CRM_BACKGROUND_TRACK.name,
                          FFAppState()
                              .userDoc
                              .permissions
                              .where((e) =>
                                  e.outletId ==
                                  FFAppState().outletDetails.outletId)
                              .toList()
                              .firstOrNull
                              ?.outletPermissions
                              ?.toList())! &&
                      !FFAppState().enabled) {
                    await actions.startBackgroundTracking();
                    FFAppState().enabled = true;
                    safeSetState(() {});
                  }
                }
              }
            } else {
              await showDialog(
                context: context,
                builder: (dialogContext) {
                  return Dialog(
                    elevation: 0,
                    insetPadding: EdgeInsets.zero,
                    backgroundColor: Colors.transparent,
                    alignment: AlignmentDirectional(0.0, 0.0)
                        .resolve(Directionality.of(context)),
                    child: GestureDetector(
                      onTap: () {
                        FocusScope.of(dialogContext).unfocus();
                        FocusManager.instance.primaryFocus?.unfocus();
                      },
                      child: CheckinpopupWidget(),
                    ),
                  );
                },
              );
            }
          }
        }
      } else {
        context.pushNamed(OutletlistWidget.routeName);
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) => safeSetState(() {}));
  }

